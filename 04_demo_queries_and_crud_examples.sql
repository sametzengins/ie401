-- 1) Part catalog (from VIEW)
SELECT '1) Part Catalog' AS Report_Name, v.* FROM vw_part_catalog v ORDER BY unit_price ASC LIMIT 20;

-- 2) Customer summary (from VIEW)
SELECT '2) Customer Summary' AS Report_Name, v.* FROM vw_customer_summary v ORDER BY total_spent DESC LIMIT 20;

-- 3) Compatible parts query (JOIN heavy)
SELECT 
    '3) Compatible Parts' AS Report_Name,
    p.part_id,
    p.part_name,
    p.part_number,
    p.unit_price,
    p.stock_quantity,
    s.store_name,
    vb.brand_name,
    vm.model_name,
    c.year_from,
    c.year_to
FROM parts p
JOIN sellers s ON p.seller_id = s.seller_id
JOIN compatibility c ON p.part_id = c.part_id
JOIN vehicle_brands vb ON c.brand_id = vb.brand_id
JOIN vehicle_models vm ON c.model_id = vm.model_id
WHERE vb.brand_name = 'Toyota'
  AND vm.model_name = 'Corolla'
  AND p.part_status = 'active'
  AND p.stock_quantity > 0
ORDER BY p.unit_price ASC;

-- 4) Top-selling parts (last 30 days) (JOIN + GROUP BY)
SELECT 
    '4) Top Selling Parts' AS Report_Name,
    p.part_id,
    p.part_name,
    SUM(oi.quantity) AS units_sold_30d,
    SUM(oi.item_total) AS revenue_30d
FROM order_items oi
JOIN orders o ON oi.order_id = o.order_id
JOIN parts p ON oi.part_id = p.part_id
WHERE o.order_status <> 'cancelled'
  AND o.order_date >= DATE_SUB(CURDATE(), INTERVAL 30 DAY)
GROUP BY p.part_id, p.part_name
ORDER BY revenue_30d DESC;

-- 5) Slow-moving parts (fixed: aggregate conditions must be in HAVING)
SELECT 
    '5) Slow Moving Parts' AS Report_Name,
    p.part_id,
    p.part_name,
    p.stock_quantity,
    MAX(o.order_date) AS last_sale_date,
    DATEDIFF(CURDATE(), MAX(o.order_date)) AS days_since_last_sale,
    COUNT(oi.order_item_id) AS total_sales_rows,
    COALESCE(SUM(oi.quantity), 0) AS total_units_sold
FROM parts p
LEFT JOIN order_items oi ON p.part_id = oi.part_id
LEFT JOIN orders o ON oi.order_id = o.order_id AND o.order_status <> 'cancelled'
WHERE p.part_status = 'active'
GROUP BY p.part_id, p.part_name, p.stock_quantity
HAVING (last_sale_date IS NULL OR DATEDIFF(CURDATE(), last_sale_date) > 90)
ORDER BY days_since_last_sale DESC;


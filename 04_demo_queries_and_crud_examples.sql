-- Step D15) Archive demo (requires archive_orders table from schema_fixed)
-- We archive a specific delivered order older than 1 year to avoid impacting seeded rows and to avoid FK errors.
SET @cutoff_date = DATE_SUB(CURDATE(), INTERVAL 1 YEAR);

-- CLEANUP first to allow re-runs without Duplicate Key Error
DELETE FROM payments WHERE order_id IN (SELECT order_id FROM orders WHERE order_number = 'ORD-2023-0999');
DELETE FROM order_items WHERE order_id IN (SELECT order_id FROM orders WHERE order_number = 'ORD-2023-0999');
DELETE FROM orders WHERE order_number = 'ORD-2023-0999';
DELETE FROM archive_orders WHERE order_number = 'ORD-2023-0999';

-- Create one delivered order older than 1 year
INSERT INTO orders (order_number, user_id, total_amount, final_amount, order_status, order_date)
VALUES ('ORD-2023-0999', 6, 100.00, 100.00, 'delivered', DATE_SUB(CURDATE(), INTERVAL 400 DAY));
SET @old_order_id = LAST_INSERT_ID();

-- Add a payment row for this archived order (to demonstrate FK-safe delete order)
INSERT INTO payments (order_id, payment_method, amount, status, transaction_id)
VALUES (@old_order_id, 'credit_card', 100.00, 'completed', CONCAT('TXN-', UUID()));


-- BEFORE: counts
SELECT 'D15) Archive Count Before' AS Step, COUNT(*) AS orders_total_before FROM orders;
SELECT 'D15) Archive Count Before' AS Step, COUNT(*) AS archive_total_before FROM archive_orders;
-- BEFORE: snapshot (row exists in orders, not in archive)
SELECT 'D15) Target Order Before' AS Step, o.* FROM orders o WHERE order_id = @old_order_id;
SELECT 'D15) Archive Content Before' AS Step, ao.* FROM archive_orders ao; 

-- Archive (insert with explicit column list)
INSERT INTO archive_orders (order_id, order_number, user_id, total_amount, final_amount, order_status, order_date)
SELECT o.order_id, o.order_number, o.user_id, o.total_amount, o.final_amount, o.order_status, o.order_date
FROM orders o
WHERE o.order_id = @old_order_id
  AND o.order_status = 'delivered'
  AND o.order_date < @cutoff_date;

-- Delete child rows first to satisfy FK constraints
DELETE FROM payments WHERE order_id = @old_order_id;
DELETE FROM order_items WHERE order_id = @old_order_id;

-- Then delete the archived order
DELETE FROM orders WHERE order_id = @old_order_id;

-- AFTER: snapshot (order removed from orders, exists in archive)
-- We select 1 row from orders to show it's gone (or remaining table data) and the specific archived row + seed
SELECT 'D15) Orders Table Post-Delete' AS Step, o.* FROM orders o WHERE order_id = @old_order_id UNION ALL SELECT 'D15) Orders Table Top 1' AS Step, o.* FROM orders o LIMIT 1; 
SELECT 'D15) Archive Table Result' AS Step, ao.* FROM archive_orders ao WHERE order_id = @old_order_id OR order_id = 1001;

-- AFTER: counts
SELECT 'D15) Orders Count After' AS Step, COUNT(*) AS orders_total_after FROM orders;
SELECT 'D15) Archive Count After' AS Step, COUNT(*) AS archive_total_after FROM archive_orders;

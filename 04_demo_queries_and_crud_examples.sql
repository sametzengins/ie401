-- Suppress warnings for initial drops
SET @OLD_SQL_NOTES=@@SQL_NOTES, SQL_NOTES=0;
DROP VIEW IF EXISTS vw_part_catalog;
SET SQL_NOTES=@OLD_SQL_NOTES;
CREATE VIEW vw_part_catalog AS
SELECT
    p.part_id,
    p.part_name,
    p.part_number,
    p.unit_price,
    p.stock_quantity,
    p.part_status,
    pc.category_name,
    s.seller_id,
    s.store_name,
    s.specialization,
    -- SUBQUERY: avg rating per part
    (
        SELECT ROUND(AVG(r.rating), 2)
        FROM reviews r
        WHERE r.part_id = p.part_id
    ) AS avg_part_rating,
    -- SUBQUERY: review count per part
    (
        SELECT COUNT(*)
        FROM reviews r2
        WHERE r2.part_id = p.part_id
    ) AS review_count
FROM parts p
JOIN part_categories pc ON p.category_id = pc.category_id
JOIN sellers s ON p.seller_id = s.seller_id;

SET @OLD_SQL_NOTES=@@SQL_NOTES, SQL_NOTES=0;
DROP VIEW IF EXISTS vw_customer_summary;
SET SQL_NOTES=@OLD_SQL_NOTES;
CREATE VIEW vw_customer_summary AS
SELECT
    u.user_id,
    CONCAT(u.first_name, ' ', u.last_name) AS customer_name,
    u.email,
    COUNT(DISTINCT cv.vehicle_id) AS vehicle_count,
    -- SUBQUERY: last order date
    (
        SELECT MAX(o.order_date)
        FROM orders o
        WHERE o.user_id = u.user_id
    ) AS last_order_date,
    -- SUBQUERY: total spent excluding cancelled
    (
        SELECT COALESCE(SUM(o2.final_amount), 0)
        FROM orders o2
        WHERE o2.user_id = u.user_id
          AND o2.order_status <> 'cancelled'
    ) AS total_spent
FROM users u
LEFT JOIN customer_vehicles cv ON u.user_id = cv.user_id
WHERE u.user_type = 'customer'
GROUP BY u.user_id, u.first_name, u.last_name, u.email;


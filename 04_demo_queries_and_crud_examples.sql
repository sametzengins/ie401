SET @OLD_SQL_NOTES=@@SQL_NOTES, SQL_NOTES=0;
DROP FUNCTION IF EXISTS fn_cart_total;
SET SQL_NOTES=@OLD_SQL_NOTES;
DELIMITER $$
CREATE FUNCTION fn_cart_total(p_cart_id INT)
RETURNS DECIMAL(10,2)
DETERMINISTIC
BEGIN
    DECLARE v_total DECIMAL(10,2);
    SELECT COALESCE(SUM(ci.quantity * ci.unit_price_snapshot), 0)
    INTO v_total
    FROM cart_items ci
    WHERE ci.cart_id = p_cart_id;
    RETURN v_total;
END$$
DELIMITER ;

SET @OLD_SQL_NOTES=@@SQL_NOTES, SQL_NOTES=0;
DROP PROCEDURE IF EXISTS sp_create_cart_for_user;
SET SQL_NOTES=@OLD_SQL_NOTES;
DELIMITER $$
CREATE PROCEDURE sp_create_cart_for_user(IN p_user_id INT, OUT p_cart_id INT)
BEGIN
    INSERT INTO carts (user_id, cart_status) VALUES (p_user_id, 'active');
    SET p_cart_id = LAST_INSERT_ID();
END$$
DELIMITER ;

-- Checkout procedure:
-- - Uses CURSOR to iterate through cart_items
-- - Inserts into orders + order_items
-- - Updates cart status
SET @OLD_SQL_NOTES=@@SQL_NOTES, SQL_NOTES=0;
DROP PROCEDURE IF EXISTS sp_checkout_cart;
SET SQL_NOTES=@OLD_SQL_NOTES;
DELIMITER $$
CREATE PROCEDURE sp_checkout_cart(IN p_cart_id INT, OUT p_order_id INT)
BEGIN
    DECLARE done INT DEFAULT 0;
    DECLARE v_user_id INT;
    DECLARE v_part_id INT;
    DECLARE v_qty INT;
    DECLARE v_unit_price DECIMAL(10,2);
    DECLARE v_seller_id INT;
    DECLARE v_total DECIMAL(10,2);

    DECLARE cur CURSOR FOR
        SELECT ci.part_id, ci.quantity, ci.unit_price_snapshot, p.seller_id
        FROM cart_items ci
        JOIN parts p ON ci.part_id = p.part_id
        WHERE ci.cart_id = p_cart_id;

    DECLARE CONTINUE HANDLER FOR NOT FOUND SET done = 1;

    -- cart owner
    SELECT user_id INTO v_user_id FROM carts WHERE cart_id = p_cart_id;

    -- create order (order_number generated by trigger if NULL/empty)
    SET v_total = fn_cart_total(p_cart_id);

    INSERT INTO orders (order_number, user_id, total_amount, final_amount, order_status)
    VALUES (NULL, v_user_id, v_total, v_total, 'pending');

    SET p_order_id = LAST_INSERT_ID();

    OPEN cur;
    read_loop: LOOP
        FETCH cur INTO v_part_id, v_qty, v_unit_price, v_seller_id;
        IF done = 1 THEN
            LEAVE read_loop;
        END IF;

        INSERT INTO order_items (order_id, part_id, seller_id, quantity, unit_price, item_total)
        VALUES (p_order_id, v_part_id, v_seller_id, v_qty, v_unit_price, v_qty * v_unit_price);
        -- stock will be updated by trigger update_stock_after_order
    END LOOP;
    CLOSE cur;

    UPDATE carts SET cart_status = 'checked_out' WHERE cart_id = p_cart_id;
END$$
DELIMITER ;

